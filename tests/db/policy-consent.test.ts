import assert from "node:assert/strict";
import { mock, test } from "node:test";
import { eq } from "drizzle-orm";
import { createCalendarFixture } from "./calendar-fixture";
import { getDatabase } from "../../lib/db/client";
import * as schema from "../../lib/db/schema";
import { cancellationPolicyText, cancellationPolicyVersion } from "../../lib/cancellation-policy-consent";
import { DrizzleReservationRepository } from "../../lib/repositories/drizzle-reservation-repository";
import { reservationApplicationDetails } from "../../lib/reservation-availability";

test("customer confirmed requests persist versioned consent, verified actor and server time atomically", async () => {
  const fixture = await createCalendarFixture();
  try {
    const { POST: create } = await import("../../app/api/reservations/route");
    const { POST: convert } = await import("../../app/api/reservations/confirmed-request/route");
    const { GET: own } = await import("../../app/api/accounts/me/reservations/route");
    await fixture.repo.createAccount({ firebaseUid: "calendar-test-user", name: "本人", contact: "consent@example.test", phone: "09012345678" });
    await fixture.repo.createAccount({ firebaseUid: "foreign", name: "別人", contact: "foreign@example.test", phone: "09012345678" });
    const base = { name: "本人", email: "consent@example.test", phone: "09012345678", date: "2099-11-15", startTime: "12:00", people: 60, menuItems: ["検証メニュー"], status: "confirmed_requested", customerAccountMode: "account" as const };
    const agreement = { accepted: true, version: cancellationPolicyVersion };
    const request = (body: object, token = "calendar-test-member", key?: string) => new Request("http://localhost/api/reservations", { method: "POST", headers: { "content-type": "application/json", ...(token ? { authorization: `Bearer ${token}` } : {}), ...(key ? { "Idempotency-Key": key } : {}) }, body: JSON.stringify(body) });
    assert.equal((await create(request(base, ""))).status, 401);
    assert.equal((await create(request(base))).status, 400);
    assert.equal((await create(request({ ...base, cancellationPolicyAgreement: { accepted: false, version: cancellationPolicyVersion } }))).status, 400);
    assert.equal((await create(request({ ...base, cancellationPolicyAgreement: { accepted: true, version: "old" } }))).status, 409);
    assert.equal((await fixture.repo.listReservations()).length, 0);
    const before = Date.now();
    const accepted = await create(request({ ...base, cancellationPolicyAgreement: { ...agreement, acceptedAt: "1900-01-01", firebaseUid: "foreign", policyText: "偽の本文" } }, undefined, "policy-consent-create-001"));
    assert.equal(accepted.status, 201, JSON.stringify(await accepted.clone().json()));
    const created = (await accepted.json()).reservation;
    assert.equal(created.policyConsents.length, 1);
    assert.equal(created.policyConsents[0].policyText, cancellationPolicyText);
    assert.equal(created.policyConsents[0].people, 60);
    assert.ok(Date.parse(created.policyConsents[0].acceptedAt) >= before);
    const replay = await create(request({ ...base, cancellationPolicyAgreement: agreement }, undefined, "policy-consent-create-001"));
    assert.equal(replay.status, 201);
    assert.equal((await replay.json()).reservation.policyConsents.length, 1);
    const db = await getDatabase();
    const [audit] = await db.select().from(schema.reservationPolicyConsent);
    assert.equal(audit.acceptedByFirebaseUid, "calendar-test-user");
    assert.equal(audit.source, "confirmed_request");
    const fetched = await own(new Request("http://localhost/api/accounts/me/reservations", { headers: { authorization: "Bearer calendar-test-member" } }));
    const ownBody = await fetched.json();
    assert.equal(ownBody.reservations[0].policyConsents[0].version, cancellationPolicyVersion);
    assert.doesNotMatch(JSON.stringify(ownBody), /acceptedByFirebaseUid|calendar-test-user/);
    const fresh = new DrizzleReservationRepository(db);
    assert.equal((await fresh.listReservations())[0].policyConsents?.[0].policyText, cancellationPolicyText);
    assert.ok(reservationApplicationDetails((await fresh.listReservations())[0]).some(row => row.value.includes(cancellationPolicyVersion) && row.value.includes("日本時間")));
    const temporary = await fixture.repo.createReservation({ ...base, status: "temporary_confirmed", accountFirebaseUid: "calendar-test-user" });
    const change = { reservationId: temporary.id, cancellationPolicyAgreement: agreement };
    assert.equal((await convert(request({ reservationId: temporary.id }))).status, 400);
    assert.equal((await convert(request({ ...change, cancellationPolicyAgreement: { accepted: true, version: "old" } }))).status, 409);
    const foreign = await fixture.repo.createReservation({ ...base, status: "temporary_confirmed", accountFirebaseUid: "foreign" });
    assert.equal((await convert(request({ ...change, reservationId: foreign.id }))).status, 403);
    assert.equal((await convert(request(change))).status, 200);
    assert.equal((await convert(request(change))).status, 200);
    const first = (await fixture.repo.listReservations()).find(r => r.id === temporary.id)!;
    assert.equal(first.policyConsents?.length, 1);
    assert.equal(first.policyAgreement?.kind, "confirmed");
    await fixture.repo.updateReservationStatus(temporary.id, "temporary_confirmed");
    await fixture.repo.updateReservation(temporary.id, { people: 55 });
    assert.equal((await convert(request(change))).status, 200);
    const history = (await fixture.repo.listReservations()).find(r => r.id === temporary.id)!.policyConsents!;
    assert.equal(history.length, 2); assert.equal(history[0].people, 60); assert.equal(history[1].people, 55);
    assert.equal(history[0].acceptedAt, first.policyConsents![0].acceptedAt);
    await fixture.repo.updateReservationStatus(temporary.id, "temporary_confirmed");
    const recordCount = (await db.select().from(schema.reservationPolicyConsent)).length;
    const reservationCount = (await fixture.repo.listReservations()).length;
    const failure = mock.method(DrizzleReservationRepository.prototype, "recordCancellationPolicyConsent", async () => { throw new Error("forced audit failure"); });
    assert.equal((await convert(request(change))).status, 500);
    assert.equal((await fixture.repo.listReservations()).find(r => r.id === temporary.id)?.status, "temporary_confirmed");
    assert.equal((await create(request({ ...base, cancellationPolicyAgreement: agreement }, undefined, "policy-consent-failure-001"))).status, 500);
    assert.equal((await fixture.repo.listReservations()).length, reservationCount);
    assert.equal((await db.select().from(schema.reservationPolicyConsent)).length, recordCount);
    assert.equal((await db.select().from(schema.reservationSubmission).where(eq(schema.reservationSubmission.requestKey, "policy-consent-failure-001"))).length, 0);
    failure.mock.restore();
    const noConsentTemp = await create(request({ ...base, status: "temporary_requested" })); assert.equal(noConsentTemp.status, 201);
    assert.equal((await noConsentTemp.json()).reservation.policyConsents.length, 0);
  } finally { mock.restoreAll(); await fixture.close(); }
});
